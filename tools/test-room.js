// Browser checks for personal room settings, bounded selection and console-only paging.
const { chromium } = require('playwright');
const { pathToFileURL } = require('node:url');
const fs = require('node:fs'), path = require('node:path'), assert = require('node:assert/strict');
(async () => {
  const root = path.resolve(__dirname, '..');
  const edge = ['C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe', 'C:/Program Files/Microsoft/Edge/Application/msedge.exe'].find(p => fs.existsSync(p));
  const browser = await chromium.launch({ headless: true, ...(edge ? { executablePath: edge } : {}) });
  const folder = path.join(root, '.cache/room-review', String(Date.now())); fs.mkdirSync(folder, { recursive: true });
  try {
    const page = await browser.newPage({ viewport: { width: 1920, height: 1080 } });
    const errors = []; page.on('pageerror', error => errors.push(error.message));
    await page.goto(pathToFileURL(path.join(root, 'index.html')).href);
    const panel = async tab => { if (!await page.locator('#settingsDialog').isVisible()) await page.click('#openAppearance'); await page.click('#tab' + tab); };
    const close = async () => page.click('#doneSettings');
    const shot = async name => {
      await page.locator('img').evaluateAll(images => Promise.all(images.map(image => { image.loading = 'eager'; return image.decode().catch(() => {}); })));
      await page.screenshot({ path: path.join(folder, name), animations: 'disabled' });
    };
    await panel('Appearance'); await page.click('#layoutShelf'); await close();
    const layout = await page.evaluate(() => {
      const tv = document.getElementById('roomTv').getBoundingClientRect(), search = document.querySelector('.browse-panel').getBoundingClientRect();
      return { tv: { x: tv.x, y: tv.y, w: tv.width, h: tv.height }, searchRight: search.right };
    });
    assert.ok(layout.searchRight < layout.tv.x - 10, 'search ends on the wall before the TV');
    assert.ok(layout.tv.x > 1100 && layout.tv.w > 500, 'TV content uses the actual screen plane');
    await shot('room-console.png');
    await page.locator('.display-tier:not([hidden]) .card-main').nth(3).focus();
    await page.keyboard.press('PageDown');
    assert.equal(await page.locator('#shelfPageStatus').textContent(), '2 / 7');
    assert.equal(await page.evaluate(() => shelfIndex), 11, 'page jump retains the same slot');
    assert.ok(await page.evaluate(() => shelfAnimations.length > 0), 'page change animates hardware');
    assert.equal(await page.evaluate(() => document.body.getAnimations().length), 0, 'the room body is never animated');
    await page.keyboard.press('PageUp'); await page.keyboard.press('PageDown');
    await page.waitForFunction(() => document.querySelectorAll('.shelf-swap-ghost').length === 0);
    assert.equal(await page.locator('.shelf-swap-ghost').count(), 0, 'rapid reversals leave no stale console copies');
    await panel('Browse'); await page.selectOption('#shelfMode', 'single'); await page.click('#tabConsoles');
    await page.click('#showAllConsoles'); assert.equal(await page.locator('input[data-console]:checked').count(), 8);
    const ninth = page.locator('input[data-console="wiiu"]'); await ninth.click();
    assert.equal(await ninth.isChecked(), false, 'a ninth console cannot enter the fixed display');
    await close(); assert.equal(await page.locator('.display-tier .card').count(), 8);
    await page.reload(); assert.equal(await page.locator('.display-tier .card').count(), 8, 'curated choice survives reopen');
    await panel('Appearance'); await page.click('#layoutGrid'); await close();
    assert.equal(await page.locator('.card').count(), 52, 'curated choices do not remove Grid consoles');
    await page.locator('.card[data-system="ps2"] .favorite').click();
    await panel('Consoles'); await page.click('#scopeFavorites'); await close();
    assert.equal(await page.locator('.card').count(), 1, 'favourites-only filter does not include non-favourites');
    await panel('Consoles'); await page.click('#scopeAll'); await page.click('#tabBrowse'); await page.selectOption('#shelfMode', 'paged');
    await page.click('#tabAppearance'); await page.click('#layoutShelf'); await page.selectOption('#motionStyle', 'reduced'); await close();
    await page.click('#shelfNext'); assert.equal(await page.evaluate(() => shelfAnimations.length), 0, 'reduced motion does not slide pages');
    await panel('Room'); await page.selectOption('#tvMode', 'message');
    await page.fill('#tvMessage', '<script>name</script> & my play room'); await close();
    assert.match(await page.locator('#roomTv').textContent(), /<script>name<\/script>/);
    assert.equal(await page.locator('#roomTv script').count(), 0, 'custom text cannot become HTML');
    await panel('Room'); await page.fill('#tvMessage', "Iswebro's play room"); await page.selectOption('#tvMode', 'clock'); await close();
    await shot('room-clock.png');
    await panel('Room'); await page.selectOption('#tvMode', 'picture');
    await page.locator('#tvPicture').setInputFiles(path.join(root, 'assets/3d-icons/ps2.png'));
    await page.waitForFunction(() => roomTv.images.has('picture')); await close();
    assert.match(await page.locator('#roomTv img').getAttribute('src'), /^blob:/);
    await page.reload(); await page.waitForFunction(() => roomTv.images.has('picture'));
    assert.match(await page.locator('#roomTv img').getAttribute('src'), /^blob:/, 'chosen image survives reopen in local storage');
    await panel('Room'); await page.selectOption('#tvMode', 'favorites'); await page.selectOption('#tvInterval', '10'); await close();
    await page.locator('.display-tier:not([hidden]) .card-main').first().focus(); await page.keyboard.press('Home');
    await page.locator('.card[data-system="ps2"] .card-main').click(); await page.click('#showLibrary');
    const games = await page.locator('.game strong').allTextContents();
    await page.locator('.game-favorite').nth(0).click(); await page.locator('.game-favorite').nth(1).click(); await page.click('#back');
    assert.ok(games.length >= 2, 'test has multiple named demo games to rotate');
    const before = await page.locator('#roomTv').textContent();
    await page.evaluate(() => { roomTv.lastTurn = Date.now() - 11000; });
    await page.waitForFunction(before => document.getElementById('roomTv').textContent !== before, before);
    assert.notEqual(await page.locator('#roomTv').textContent(), before, 'multiple favourite games alternate on the selected interval');
    await shot('room-favourites.png');
    await panel('Room'); await page.selectOption('#tvMode', 'intro'); await page.selectOption('#introScope', 'installed');
    await page.selectOption('#introConsole', 'ps2'); await page.locator('#introPicture').setInputFiles(path.join(root, 'assets/shelf-icon.png'));
    await page.waitForFunction(() => roomTv.images.has('intro:ps2')); await close();
    await page.evaluate(() => selectShelf(shelfCards.findIndex(card => card.dataset.system === 'ps2')));
    assert.match(await page.locator('#roomTv img').getAttribute('src'), /^blob:/, 'custom intro picture replaces the artwork fallback');
    await page.evaluate(() => selectShelf(shelfCards.findIndex(card => card.dataset.system === 'switch2')));
    assert.match(await page.locator('#roomTv').textContent(), /Your play room/, 'uninstalled console does not trigger an installed-only intro');
    await panel('Room'); await page.selectOption('#introScope', 'all'); await close();
    assert.match(await page.locator('#roomTv').textContent(), /Nintendo Switch 2/, 'all-consoles intro choice includes references honestly');
    await page.setViewportSize({ width: 390, height: 844 });
    assert.equal(await page.locator('#roomTv').isVisible(), false, 'cropped-away TV does not spill over the phone controls');
    assert.equal(await page.locator('.display-tier:not([hidden]) .card').count(), 4, 'phone still pages at its physical capacity');
    await shot('room-mobile.png');
    assert.deepEqual(errors, []);
    fs.writeFileSync(path.join(folder, 'checks.json'), JSON.stringify({ status: 'passed', scope: 'PC preview, not console acceptance', errors }, null, 2) + '\n');
    fs.writeFileSync(path.join(root, '.cache/room-review/latest.json'), JSON.stringify({ folder, passed: true }, null, 2) + '\n');
    console.log('PASS: room geometry, console-only page swaps, capped curated choice, persistence, favourites, text safety, local images, clock, rotation, intro scope and phone layout.');
  } finally { await browser.close(); }
})().catch(error => { console.error(error); process.exitCode = 1; });
