// One measured room coordinate system for the browser and native renderer.
const fs=require('node:fs'),path=require('node:path'),crypto=require('node:crypto'),assert=require('node:assert/strict');
const root=path.resolve(__dirname,'..'),manifest=JSON.parse(fs.readFileSync(path.join(root,'assets/backgrounds/manifest.json'),'utf8'));
const scene=manifest.scene;
assert.equal(manifest.schema,1);assert.equal(manifest.assets.length,2);assert.equal(scene.columns,4);assert.equal(scene.rows.length,2);
for(const item of manifest.assets){
 assert.match(item.local,/^assets\/backgrounds\/[a-z0-9-]+\.png$/);
 const raw=fs.readFileSync(path.join(root,item.local));assert.equal(raw.length,item.bytes);
 assert.equal(crypto.createHash('sha256').update(raw).digest('hex'),item.sha256);
 assert.equal(raw.readUInt32BE(16),scene.width);assert.equal(raw.readUInt32BE(20),scene.height);
}
assert.ok(manifest.assets.some(a=>a.local===scene.base)&&manifest.assets.some(a=>a.local===scene.shelf));
assert.ok(0<=scene.left&&scene.left<scene.right&&scene.right<=scene.width);
for(const row of scene.rows)assert.ok(0<row.woodTop&&row.woodTop<row.feet&&row.feet<row.woodEnd&&row.woodEnd<row.label&&row.label<scene.height&&row.artHeight>0);
assert.ok(scene.tv.x>scene.width/2&&scene.tv.x+scene.tv.width<scene.width&&scene.tv.y>0&&scene.tv.y+scene.tv.height<scene.rows[0].woodTop);
fs.writeFileSync(path.join(root,'assets/backgrounds/scene.js'),'// Generated from the measured room manifest.\nwindow.shelfRoomScene = '+JSON.stringify(scene,null,2)+';\n');
const header=`// SPDX-License-Identifier: GPL-3.0-only
// Generated by tools/build-scene-layout.js; edit the measured room manifest.
#pragma once
#include <array>
namespace shelf::room_scene {
inline constexpr int width=${scene.width}, height=${scene.height}, left=${scene.left}, right=${scene.right}, columns=${scene.columns};
inline constexpr const char* base_image="${scene.base}";
inline constexpr const char* shelf_image="${scene.shelf}";
inline constexpr int tv_x=${scene.tv.x}, tv_y=${scene.tv.y}, tv_width=${scene.tv.width}, tv_height=${scene.tv.height};
struct Tier { int wood_top, wood_end, feet, label, art_height; };
inline constexpr std::array<Tier,2> tiers = {{${scene.rows.map(r=>`{${r.woodTop},${r.woodEnd},${r.feet},${r.label},${r.artHeight}}`).join(',')}}};
} // namespace shelf::room_scene
`;
fs.writeFileSync(path.join(root,'native/include/shelf/scene.generated.hpp'),header);
console.log('Verified room assets and generated shared browser/native shelf coordinates.');
