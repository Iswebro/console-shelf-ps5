// Hardware metadata only. Runtime detection supplies availability and game counts.
const fs = require('node:fs');
const path = require('node:path');
const systems = require('../systems-data.js');
const brands = ['', ...new Set(systems.map(system => system.family))];
const rows = systems.map(system => `    {${[system.id, system.name, system.family, system.image, system.core || ''].map(value => JSON.stringify(value)).join(', ')}, ${system.year || 0}}`).join(',\n');
const output = `// Generated by tools/build-native-catalog.js. SPDX-License-Identifier: GPL-3.0-only
#pragma once
#include <array>
#include <cstddef>
#include <string_view>

namespace shelf {
struct SystemDefinition {
    std::string_view id, name, brand, image, suggested_core;
    int year;
};
inline constexpr std::array<SystemDefinition, ${systems.length}> catalog = {{
${rows}
}};
inline constexpr std::size_t system_count = catalog.size();
inline constexpr std::array<std::string_view, ${brands.length}> brands = {${brands.map(value => JSON.stringify(value)).join(', ')}};
} // namespace shelf
`;
const target = path.resolve(__dirname, '../native/include/shelf/catalog.generated.hpp');
fs.mkdirSync(path.dirname(target), { recursive: true });
fs.writeFileSync(target, output);
console.log(`Generated ${systems.length} native system definitions without demo games or installed-status claims.`);
